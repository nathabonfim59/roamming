package ui

import "image/color"

// paletteHex maps Roam glow palette names to approximate colors for
// rendering the picker swatches. The API only ever receives the name —
// Roam clients resolve names to their own light/dark hex values.
var paletteHex = map[string]color.RGBA{
	"blue":   {0x3B, 0x82, 0xF6, 0xFF},
	"gold":   {0xC9, 0xA2, 0x27, 0xFF},
	"gray":   {0x6B, 0x72, 0x80, 0xFF},
	"green":  {0x22, 0xC5, 0x5E, 0xFF},
	"indigo": {0x63, 0x66, 0xF1, 0xFF},
	"lime":   {0x84, 0xCC, 0x16, 0xFF},
	"orange": {0xF9, 0x73, 0x16, 0xFF},
	"pink":   {0xEC, 0x48, 0x99, 0xFF},
	"purple": {0xA8, 0x55, 0xF7, 0xFF},
	"red":    {0xEF, 0x44, 0x44, 0xFF},
	"teal":   {0x14, 0xB8, 0xA6, 0xFF},
	"yellow": {0xEA, 0xB3, 0x08, 0xFF},
}

// swatchColor returns the picker color for a palette name.
func swatchColor(name string) (color.RGBA, bool) {
	c, ok := paletteHex[name]
	return c, ok
}
